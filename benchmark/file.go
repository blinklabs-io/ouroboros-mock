package benchmark

import (
	"fmt"
	"os"
)

func openRegular(root *os.Root, path string) (*os.File, error) {
	f, err := openArtifact(root, path)
	if err != nil {
		return nil, err
	}
	info, err := f.Stat()
	if err != nil {
		_ = f.Close()
		return nil, err
	}
	if !info.Mode().IsRegular() {
		_ = f.Close()
		return nil, fmt.Errorf("not a regular artifact: %s", path)
	}
	return f, nil
}
